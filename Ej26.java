import java.util.*;
public class Ej26 {
  public static void main(String args[]) {
   int saldo = 100;
   saldo += 50;
   System.out.println("Saldo + 50 : " + saldo);
   saldo -= 20;
   System.out.println("Saldo - 20 : " + saldo);
   saldo *= 2;
   System.out.println("Saldo duplicado : " + saldo);
   saldo /= 4;
   System.out.println("Saldo entre 4 : " + saldo);
  }
}